"""Генерация идентификаторов записей."""

from __future__ import annotations

import uuid

# 48 бит: коллизия между существующими записями практически исключена
# (32 бита прежних 8-символьных ID с ростом базы могли дать дубль, который
# молча ломал row_index и обновления). Формат файла не меняется: старые
# 8-символьные ID остаются валидными.
_ID_LENGTH = 12


def new_id() -> str:
    """Случайный hex-идентификатор записей склада."""
    return uuid.uuid4().hex[:_ID_LENGTH]

"""Цвета ящиков: фиксированная палитра и авто-выбор по ID.

Цвет нужен интерфейсу, чтобы отличать ящики глазами. Он выбирается один раз
при создании и хранится в колонке «Цвет» листа «Ящики». Выбор
детерминированный (SHA-256 от ID), поэтому один и тот же ящик всегда даёт
один и тот же цвет, а цвета распределяются по палитре равномерно. Тот же
функционал служит значением по умолчанию для ящиков, созданных до появления
колонки (пустой «Цвет» в файле).
"""

from __future__ import annotations

import hashlib

# Палитра интерфейса: различимые цвета, читаются на светлой и тёмной теме.
BOX_PALETTE = [
    "#EF4444",  # красный
    "#F97316",  # оранжевый
    "#EAB308",  # жёлтый
    "#84CC16",  # лайм
    "#10B981",  # изумрудный
    "#14B8A6",  # бирюзовый
    "#0EA5E9",  # небесный
    "#3B82F6",  # синий
    "#8B5CF6",  # фиолетовый
    "#EC4899",  # розовый
]


def pick_box_color(box_id: str) -> str:
    """Стабильно выбирает цвет из палитры по ID ящика."""
    digest = hashlib.sha256(str(box_id).encode("utf-8")).hexdigest()
    return BOX_PALETTE[int(digest, 16) % len(BOX_PALETTE)]
